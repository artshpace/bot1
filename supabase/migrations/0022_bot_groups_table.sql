create table if not exists public.bot_groups (
  id          text primary key,          -- 'g1', 'v1', 'a1' … (как в старом BOT_GROUPS)
  dir         text not null,             -- «Гитара», «Вокал» …
  age         text not null,             -- «7–10 лет», «18+», «разный возраст» …
  teacher     text not null,
  days        jsonb not null,            -- [1,3,5] — 0=Вс … 6=Сб
  time        text not null,             -- "HH:MM", Almaty
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);
alter table public.bot_groups enable row level security;
-- Политик нет намеренно: доступ только у воркера (service_role), который RLS обходит.

